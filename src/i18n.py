def set_lang(code):
    global LANG
    if code in STRINGS:
        LANG = code
    return LANG


def current():
    return LANG


def t(key, **kw):
    """取翻译。找不到的键原样返回，方便发现漏翻。"""
    table = STRINGS.get(LANG) or STRINGS['zh']
    s = table.get(key)
    if s is None:
        s = STRINGS['zh'].get(key, key)
    if kw:
        try:
            return s.format(**kw)
        except Exception:
            return s
    return s


def is_zh():
    return LANG == 'zh'
